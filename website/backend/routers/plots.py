"""
Plots router — serves PNG plot images generated by export_artifacts.py.
Frontend can display these directly as <img src="/api/plots/clf_rf_confusion.png"> tags.
"""
from __future__ import annotations
from pathlib import Path

from fastapi import APIRouter, HTTPException
from fastapi.responses import FileResponse

from backend.config import ARTIFACT_DIR
from backend.core.schemas import PlotListResponse

router = APIRouter(prefix="/api/plots", tags=["plots"])

PLOTS_DIR = ARTIFACT_DIR / "plots"

# All expected plot filenames with labels for the frontend
PLOT_CATALOG = {
    # Preprocessing
    "preprocessing_class_dist.png":  "Class Distribution",
    "preprocessing_pca_2d.png":      "PCA 2D Scatter",
    "preprocessing_pca_scree.png":   "PCA Scree (Variance)",
    # Classification — per model
    "clf_random_forest_confusion.png":    "Random Forest — Confusion Matrix",
    "clf_random_forest_roc.png":          "Random Forest — ROC Curve",
    "clf_adaboost_confusion.png":         "AdaBoost — Confusion Matrix",
    "clf_adaboost_roc.png":               "AdaBoost — ROC Curve",
    "clf_gradient_boosting_confusion.png":"Gradient Boosting — Confusion Matrix",
    "clf_gradient_boosting_roc.png":      "Gradient Boosting — ROC Curve",
    "clf_bagging_confusion.png":          "Bagging — Confusion Matrix",
    "clf_bagging_roc.png":                "Bagging — ROC Curve",
    "clf_mlp_confusion.png":              "MLP — Confusion Matrix",
    "clf_mlp_roc.png":                    "MLP — ROC Curve",
    "clf_comparison_bar.png":            "Classification — Model Comparison",
    # Regression
    "reg_pred_vs_actual.png":       "Regression — Predicted vs Actual",
    "reg_comparison_bar.png":       "Regression — Model Comparison (R²)",
    # Clustering
    "cluster_elbow.png":            "K-Means — Elbow Curve",
    "cluster_dendrogram.png":       "Agglomerative — Dendrogram",
    "cluster_pca2d.png":            "Clustering — PCA 2D Scatter",
    "cluster_silhouette.png":       "Clustering — Silhouette vs k",
}


@router.get("", response_model=PlotListResponse)
async def list_plots() -> PlotListResponse:
    """Return the list of available plot filenames."""
    available = [
        name for name in PLOT_CATALOG
        if (PLOTS_DIR / name).exists()
    ]
    return PlotListResponse(plots=available)


@router.get("/catalog")
async def get_catalog() -> dict:
    """Return all plot filenames with their human-readable labels and availability."""
    return {
        name: {
            "label": label,
            "available": (PLOTS_DIR / name).exists(),
            "url": f"/api/plots/{name}",
        }
        for name, label in PLOT_CATALOG.items()
    }


@router.get("/{filename}")
async def get_plot(filename: str) -> FileResponse:
    """Serve a single plot PNG by filename."""
    # Security: only allow simple filenames, no path traversal
    if "/" in filename or "\\" in filename or ".." in filename:
        raise HTTPException(status_code=400, detail="Invalid filename")
    if not filename.endswith(".png"):
        raise HTTPException(status_code=400, detail="Only PNG files are served here")

    path = PLOTS_DIR / filename
    if not path.exists():
        raise HTTPException(
            status_code=404,
            detail=f"Plot '{filename}' not found. Run: python notebooks/export_artifacts.py"
        )
    return FileResponse(path, media_type="image/png")
